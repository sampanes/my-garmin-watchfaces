#!/usr/bin/env python
"""Where each piece stands on each foreground (2026-11-05): placed by hand.

Every foreground is its own painting, so one fixed spot for a piece fits
none of them well (the village and the lantern showed it). John placed each
piece on each of the ten paintings from placement sheets (the face under a
lettered grid, one cell 16 px, every piece to scale beside it), as moves
from a first guess; SPOTS is the result, in px on the 416 face: the piece's
center x and its foot y (the bottom of its bitmap).

    lantern   low battery; drawn just behind the foreground, so the
              painting's grass stands in front of it and blends it in
    heron, deer, torii, bridge
              the valley pieces (one shows at a time); placed now, drawn
              once their signals are built (PROCEDURE.md, the signals)
    swallow   unread notifications, one spot for every painting, 24 px

The pagoda is left out (John: it looked silly everywhere); the boat and the
village are held. Rows follow the foreground order of bake_foregrounds.py
(foreground_table.json), which the Scene's foregroundIndex indexes.

Writes:
    watch-faces/japanese-ink-heartrate/source/JapaneseInkHeartrateSpots.mc
    scripts/spot_table.json    the same table for the mock

    py -3.11 scripts/bake_spots.py           write the tables
    py -3.11 scripts/bake_spots.py --check   exit 1 if a table is stale
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FACE = os.path.join(HERE, "..", "watch-faces", "japanese-ink-heartrate")
MC = os.path.join(FACE, "source", "JapaneseInkHeartrateSpots.mc")
JSON = os.path.join(HERE, "spot_table.json")
FG_TABLE = os.path.join(HERE, "foreground_table.json")
FACE_PX = 416

PIECES = ("lantern", "heron", "deer", "torii", "bridge")
# foreground: {piece: (center x, foot y)} px on the 416 face (John, 11-05)
SPOTS = [
    ("fg_spring_b", {"lantern": (280, 387), "heron": (210, 389), "deer": (210, 389), "torii": (210, 389), "bridge": (210, 389)}),
    ("fg_spring_a", {"lantern": (260, 347), "heron": (199, 357), "deer": (199, 357), "torii": (199, 357), "bridge": (199, 357)}),
    ("fg_summer_b", {"lantern": (284, 364), "heron": (193, 373), "deer": (193, 373), "torii": (193, 373), "bridge": (193, 373)}),
    ("fg_summer_a", {"lantern": (288, 328), "heron": (225, 357), "deer": (225, 357), "torii": (225, 341), "bridge": (225, 341)}),
    ("fg_autumn_b", {"lantern": (320, 354), "heron": (210, 405), "deer": (210, 405), "torii": (210, 405), "bridge": (210, 405)}),
    ("fg_autumn_c", {"lantern": (352, 315), "heron": (230, 357), "deer": (230, 357), "torii": (230, 357), "bridge": (230, 357)}),
    ("fg_winter_b", {"lantern": (272, 359), "heron": (209, 389), "deer": (209, 389), "torii": (209, 389), "bridge": (209, 389)}),
    ("fg_winter_c", {"lantern": (392, 271), "heron": (220, 357), "deer": (220, 357), "torii": (220, 357), "bridge": (220, 357)}),
    ("fg_pass_b", {"lantern": (328, 313), "heron": (196, 384), "deer": (208, 384), "torii": (208, 384), "bridge": (208, 384)}),
    ("fg_pass_c", {"lantern": (332, 300), "heron": (229, 357), "deer": (229, 357), "torii": (205, 357), "bridge": (205, 357)}),
]
SWALLOW = (324, 125)   # center x, foot y; the same on every painting


def tables():
    order = [f["name"] for f in json.load(open(FG_TABLE))["foregrounds"]]
    names = [n for n, _ in SPOTS]
    if names != order:
        raise SystemExit("SPOTS rows %s do not follow foreground_table.json %s" % (names, order))
    js = json.dumps({"face": FACE_PX, "swallow": list(SWALLOW),
                     "spots": [{"name": n, **{p: list(s[p]) for p in PIECES}} for n, s in SPOTS]},
                    indent=1) + "\n"
    mc = ["// Generated by scripts/bake_spots.py; do not edit.",
          "// Where each piece stands on each foreground, placed by hand (John, 11-05):",
          "// px on the %d face, the piece's center x and foot y, one entry per" % FACE_PX,
          "// foreground in foregroundIndex order.", ""]
    for p in PIECES:
        mc.append("const SPOT_%s_X = [%s];" % (p.upper(), ", ".join(str(s[p][0]) for _, s in SPOTS)))
        mc.append("const SPOT_%s_FOOT = [%s];" % (p.upper(), ", ".join(str(s[p][1]) for _, s in SPOTS)))
    mc += ["const SPOT_SWALLOW_X = %d;" % SWALLOW[0], "const SPOT_SWALLOW_FOOT = %d;" % SWALLOW[1],
           "const SPOT_FACE = %d.0;" % FACE_PX, ""]
    return {JSON: js, MC: "\n".join(mc)}


def main(argv):
    stale = 0
    for path, text in tables().items():
        if "--check" in argv:
            cur = open(path).read() if os.path.exists(path) else None
            if cur != text:
                print("stale:", os.path.relpath(path, os.path.join(HERE, "..")))
                stale += 1
        else:
            with open(path, "w", newline="\n") as f:
                f.write(text)
            print("wrote", os.path.relpath(path, os.path.join(HERE, "..")))
    if "--check" in argv:
        print("spots:", "current" if not stale else "%d stale" % stale)
        return 1 if stale else 0
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
