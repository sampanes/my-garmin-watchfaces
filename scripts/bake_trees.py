#!/usr/bin/env python
"""The ridge trees (2026-11-05): small tree silhouettes the face stands on a
fitted mountain's ridge where the heart rate rose a little above the shape.

The art is the trees-b sheet (art/sheets/2026-11-05_trees-b.png, ChatGPT;
prompt in art/sheets/PROMPTS.md, round 8), cut by scripts/cut_art_kit.py
into art/cuts/trees-b/. Each tree in TREES is cropped to its ink and baked
at every height in SIZES, day and night, so the watch draws it 1:1 with
drawBitmap and never scales it.

Writes into watch-faces/japanese-ink-heartrate:
    resources/drawables/tree_<name>_<h>.png, ..._night.png
    resources/drawables/trees.xml          their bitmap declarations
    source/JapaneseInkHeartrateTrees.mc    the size table and the loader
and scripts/tree_table.json, the same table for the mock.

    py -3.11 scripts/bake_trees.py           cut (if needed), bake, write tables
    py -3.11 scripts/bake_trees.py --check   exit 1 if a table is stale (no scipy)

A tree's foot is where its trunk meets the ground: the middle of the opaque
pixels (alpha >= 128) in the lowest row that has any."""
import json
import os
import sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
FACE = os.path.join(HERE, "..", "watch-faces", "japanese-ink-heartrate")
DRAW = os.path.join(FACE, "resources", "drawables")
CUTS = os.path.join(FACE, "art", "cuts", "trees-b")
MC = os.path.join(FACE, "source", "JapaneseInkHeartrateTrees.mc")
XML = os.path.join(DRAW, "trees.xml")
JSON = os.path.join(HERE, "tree_table.json")

# The trees-b cells used (number, name). Left out: the broadleaf (8) and the
# rows of five (9, 10) as too wide for one bump, the bare tree (11, hairline
# at 12 px), the snow pine (12, its snow vanishes at night), the umbrella
# pines (13, 14, acacias more than pines) and the cypress pair (16).
TREES = [(1, "pine_narrow"), (2, "pine_wide"), (3, "pine_lean_l"), (4, "pine_lean_r"),
         (5, "pines2"), (6, "pines3"), (7, "fir"), (15, "cypress")]
SIZES = (12, 16, 22)
INK_FLOOR = 0.05 * 255


def camel(name):
    return "".join(p.capitalize() for p in name.split("_"))


def bitmap_name(name, h, night=False):
    return "tree_%s_%d%s" % (name, h, "_night" if night else "")


def ensure_cuts():
    if os.path.isdir(CUTS):
        return
    import glob
    import cut_art_kit as kit
    sheet = glob.glob(os.path.join(kit.SHEETS, "20*_trees-b.png"))[0]
    kit.one(sheet, CUTS, *kit.RECIPE["trees"])


def bake_all():
    import glob
    ensure_cuts()
    keep = {bitmap_name(n, h, night) for _, n in TREES for h in SIZES for night in (False, True)}
    for path in glob.glob(os.path.join(DRAW, "tree_*.png")):
        if os.path.basename(path)[:-4] not in keep:
            os.remove(path)
            print("removed", os.path.basename(path))
    for num, name in TREES:
        day = Image.open(os.path.join(CUTS, "%02d_%s.png" % (num, name))).convert("RGBA")
        night = Image.open(os.path.join(CUTS, "%02d_%s_night.png" % (num, name))).convert("RGBA")
        a = np.asarray(day.getchannel("A"))
        ys, xs = np.nonzero(a > INK_FLOOR)
        box = (int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1)
        for h in SIZES:
            w = max(1, int(round((box[2] - box[0]) * h / float(box[3] - box[1]))))
            for im, is_night in ((day, False), (night, True)):
                out = im.crop(box).resize((w, h), Image.LANCZOS)
                out.save(os.path.join(DRAW, bitmap_name(name, h, is_night) + ".png"), optimize=True)
        print("baked", name, box[2] - box[0], "x", box[3] - box[1], "->", SIZES, flush=True)


def measure(name, h):
    a = np.asarray(Image.open(os.path.join(DRAW, bitmap_name(name, h) + ".png")).getchannel("A"))
    rows = [y for y in range(a.shape[0]) if (a[y] >= 128).any()]
    cols = np.nonzero(a[rows[-1]] >= 128)[0]
    return {"w": int(a.shape[1]), "foot": int(round(0.5 * (cols[0] + cols[-1])))}


def tables():
    m = [[measure(n, h) for h in SIZES] for _, n in TREES]
    table = {"sizes": list(SIZES),
             "trees": [{"name": n, "w": [c["w"] for c in row], "foot": [c["foot"] for c in row]}
                       for (_, n), row in zip(TREES, m)]}
    js = json.dumps(table, indent=1) + "\n"

    xml = ['<drawables xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
           'xsi:noNamespaceSchemaLocation="https://developer.garmin.com/downloads/connect-iq/resources.xsd">',
           "    <!-- Generated by scripts/bake_trees.py; do not edit. -->"]
    for _, n in TREES:
        for h in SIZES:
            for night in (False, True):
                xml.append('    <bitmap id="%s" filename="%s.png" dithering="none" '
                           'automaticPalette="false" packingFormat="png" compress="false" />'
                           % (camel(bitmap_name(n, h, night)), bitmap_name(n, h, night)))
    xml.append("</drawables>")
    xml = "\n".join(xml) + "\n"

    def arr(vals):
        return "[" + ", ".join(str(v) for v in vals) + "] as Lang.Array<Lang.Number>"
    mc = ["using Toybox.Graphics;", "using Toybox.Lang;", "using Toybox.WatchUi;", "",
          "// Generated by scripts/bake_trees.py; do not edit.",
          "// The ridge trees: %d tree silhouettes, each baked at %d heights (treeSizes())," % (len(TREES), len(SIZES)),
          "// drawn 1:1. treeW() and treeFoot() hold, tree after tree and size after size,",
          "// the bitmap's width and the x of its foot (where the trunk meets the ridge).", "",
          "const TREE_COUNT = %d;" % len(TREES), "const TREE_SIZES = %d;" % len(SIZES), "",
          "function treeSizes() as Lang.Array<Lang.Number> {", "    return %s;" % arr(SIZES), "}", "",
          "function treeW() as Lang.Array<Lang.Number> {",
          "    return %s;" % arr(v for t in table["trees"] for v in t["w"]), "}", "",
          "function treeFoot() as Lang.Array<Lang.Number> {",
          "    return %s;" % arr(v for t in table["trees"] for v in t["foot"]), "}", "",
          "// Tree i at size k, day or night; the caller catches a refusal.",
          "function loadTreeBitmap(i as Lang.Number, k as Lang.Number, night as Lang.Boolean) as Graphics.BitmapType? {",
          "    var c = i * TREE_SIZES + k;"]
    for night in (False, True):
        mc.append("    if (%snight) {" % ("" if night else "!"))
        c = 0
        for _, n in TREES:
            for h in SIZES:
                mc.append("        if (c == %d) { return WatchUi.loadResource(Rez.Drawables.%s) as Graphics.BitmapType; }"
                          % (c, camel(bitmap_name(n, h, night))))
                c += 1
        mc.append("    }")
    mc += ["    return null;", "}", ""]
    return {JSON: js, XML: xml, MC: "\n".join(mc)}


def main(argv):
    if "--check" not in argv:
        bake_all()
    stale = 0
    for path, text in tables().items():
        if "--check" in argv:
            cur = open(path).read() if os.path.exists(path) else None
            if cur != text:
                print("stale:", os.path.relpath(path, os.path.join(HERE, "..")))
                stale += 1
        else:
            with open(path, "w", newline="\n") as f:
                f.write(text)
            print("wrote", os.path.relpath(path, os.path.join(HERE, "..")))
    if "--check" in argv:
        print("ridge trees:", "current" if not stale else "%d stale" % stale)
        return 1 if stale else 0
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
