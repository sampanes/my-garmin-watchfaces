"""Generated resources for the bitmap-budget probe (scripts/bitmap-budget.ps1).

    python gen_budget_bitmaps.py <count>

Writes <count> PNGs into watch-faces/bitmap-budget-probe/resources-gen/
drawables, cycling through the ink face's real baked planes (*_cut*.png, so
sizes and compression match what the face ships), each made unique by one
nearly invisible pixel so no tool can fold two into one; the drawables.xml
that declares them as B0..B<count-1> with the face's own bitmap options; and
source-gen/BudgetIds.mc whose budgetIds() lists them. Prints the total PNG
bytes on its last line."""
import glob
import os
import shutil
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
FACE = os.path.join(REPO, "watch-faces", "japanese-ink-heartrate", "resources", "drawables")
PROBE = os.path.join(REPO, "watch-faces", "bitmap-budget-probe")
ATTRS = 'dithering="none" automaticPalette="false" packingFormat="png" compress="false"'


def main(argv):
    count = int(argv[0])
    sources = sorted(glob.glob(os.path.join(FACE, "*_cut*.png")))
    if not sources:
        sys.exit("no *_cut*.png in " + FACE + " (run scripts/gen_shape_library.py)")
    res = os.path.join(PROBE, "resources-gen")
    src = os.path.join(PROBE, "source-gen")
    for d in (res, src):
        shutil.rmtree(d, ignore_errors=True)
    os.makedirs(os.path.join(res, "drawables"))
    os.makedirs(src)

    lines = ['<drawables xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
             'xsi:noNamespaceSchemaLocation="https://developer.garmin.com/downloads/connect-iq/resources.xsd">']
    total = 0
    for i in range(count):
        img = Image.open(sources[i % len(sources)]).convert("RGBA")
        w, h = img.size
        img.putpixel((i % w, h - 1), (i & 255, (i >> 8) & 255, 7, 1))
        name = "b%d.png" % i
        path = os.path.join(res, "drawables", name)
        img.save(path, optimize=True)
        total += os.path.getsize(path)
        lines.append('    <bitmap id="B%d" filename="%s" %s />' % (i, name, ATTRS))
    lines.append("</drawables>")
    with open(os.path.join(res, "drawables", "drawables.xml"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    ids = ", ".join("Rez.Drawables.B%d" % i for i in range(count))
    with open(os.path.join(src, "BudgetIds.mc"), "w", newline="\n") as f:
        f.write("using Toybox.Lang;\n\n"
                "// Generated by scripts/gen_budget_bitmaps.py; not committed.\n"
                "function budgetIds() as Lang.Array<Lang.ResourceId> {\n"
                "    return [%s] as Lang.Array<Lang.ResourceId>;\n"
                "}\n" % ids)
    print("generated %d bitmaps, %d PNG bytes" % (count, total))


if __name__ == "__main__":
    main(sys.argv[1:])
